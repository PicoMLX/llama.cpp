import {
	cp,
	lstat,
	mkdtemp,
	readdir,
	readFile,
	rename,
	rm,
	stat,
	writeFile
} from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';

const PICO_GUIDE = `<!--
  This is the Pico Server build of the frontend.
  It is automatically generated by npm run build:pico.
  Do not edit this file directly.
-->`;
const RUNTIME_ASSETS = [
	'build.json',
	'_app/version.json',
	'locales/en.json',
	'favicon.svg',
	'favicon-dark.svg',
	'recommended-mcp/exa.ico',
	'recommended-mcp/github-light.png',
	'recommended-mcp/github-dark.png',
	'recommended-mcp/context7.png',
	'recommended-mcp/huggingface.ico'
];

async function listFiles(directory) {
	const files = [];

	for (const entry of await readdir(directory, { withFileTypes: true })) {
		const path = join(directory, entry.name);

		if (entry.isDirectory()) files.push(...(await listFiles(path)));
		else files.push(path);
	}

	return files;
}

async function validateReference(root, sourceFile, reference) {
	if (!reference || reference.startsWith('#') || reference.startsWith('//')) return;

	if (/^[a-z][a-z\d+.-]*:/i.test(reference)) return;

	const pathname = decodeURIComponent(reference.split(/[?#]/, 1)[0]);

	if (!pathname) return;

	const path = pathname.startsWith('/')
		? resolve(root, `.${pathname}`)
		: resolve(dirname(sourceFile), pathname);
	const fromRoot = relative(root, path);

	if (fromRoot === '..' || fromRoot.startsWith('../') || isAbsolute(fromRoot)) {
		throw new Error(`Pico asset escapes package: ${reference}`);
	}

	try {
		if (!(await stat(path)).isFile()) throw new Error();
	} catch {
		throw new Error(`Missing Pico asset ${reference} referenced by ${relative(root, sourceFile)}`);
	}
}

function htmlReferences(html) {
	const references = [];

	for (const [tag] of html.matchAll(/<(?:link|script|img|source|audio|video|iframe)\b[^>]*>/gi)) {
		for (const match of tag.matchAll(/\b(?:src|href|poster)\s*=\s*(["'])(.*?)\1/gi)) {
			references.push(match[2]);
		}
	}

	for (const match of html.matchAll(/\bimport\s*\(\s*(["'])(.*?)\1\s*\)/g)) {
		references.push(match[2]);
	}

	return references;
}

export async function validatePicoPackage(directory) {
	const root = resolve(directory);
	const indexPath = join(root, 'index.html');
	const html = await readFile(indexPath, 'utf8');
	const references = htmlReferences(html);

	if (!references.some((value) => /\.js(?:[?#]|$)/.test(value))) {
		throw new Error('Pico package must reference an external JavaScript bundle');
	}

	if (!references.some((value) => /\.css(?:[?#]|$)/.test(value))) {
		throw new Error('Pico package must reference an external stylesheet');
	}

	for (const path of await listFiles(root)) {
		if (path.endsWith('.html')) {
			const page = path === indexPath ? html : await readFile(path, 'utf8');

			for (const reference of htmlReferences(page)) await validateReference(root, path, reference);
		}

		if (!path.endsWith('.css')) continue;

		const css = await readFile(path, 'utf8');

		for (const match of css.matchAll(/url\(\s*(["']?)(.*?)\1\s*\)/gi)) {
			await validateReference(root, path, match[2].trim());
		}
	}

	for (const path of RUNTIME_ASSETS) {
		await validateReference(root, indexPath, path);
	}

	for (const path of ['build.json', '_app/version.json']) {
		const data = JSON.parse(await readFile(join(root, path), 'utf8'));

		if (typeof data.version !== 'string' || !data.version) {
			throw new Error(`Pico package has no version in ${path}`);
		}
	}

	JSON.parse(await readFile(join(root, 'locales/en.json'), 'utf8'));
}

async function preparePicoPackage(directory, logoPath) {
	const indexPath = join(directory, 'index.html');
	const logo = await readFile(logoPath, 'utf8');
	const html = (await readFile(indexPath, 'utf8')).replace(/<link\b[^>]*>/gi, (tag) => {
		const rel = tag.match(/\brel\s*=\s*(["'])(.*?)\1/i)?.[2].toLowerCase();

		return ['icon', 'manifest', 'apple-touch-icon', 'apple-touch-startup-image'].includes(rel)
			? ''
			: tag;
	});

	if (!html.includes('</head>')) throw new Error('Pico package is missing its HTML head');

	await writeFile(join(directory, 'favicon.svg'), logo.replaceAll('currentColor', '#111111'));
	await writeFile(join(directory, 'favicon-dark.svg'), logo.replaceAll('currentColor', '#fafafa'));
	await writeFile(
		indexPath,
		`${PICO_GUIDE}\n${html.replace('</head>', '<link rel="icon" href="favicon.svg" sizes="any" type="image/svg+xml" />\n</head>')}`
	);
}

export async function publishPicoPackage(buildDirectory, htmlDirectory, { logoPath }) {
	const destination = join(htmlDirectory, 'webui');
	const transaction = await mkdtemp(join(htmlDirectory, '.webui-stage-'));
	const next = join(transaction, 'next');
	const previous = join(transaction, 'previous');

	let preserveBackup = false;

	try {
		await cp(buildDirectory, next, { recursive: true });
		await preparePicoPackage(next, logoPath);
		await validatePicoPackage(next);

		const current = await lstat(destination).catch((error) => {
			if (error.code === 'ENOENT') return null;

			throw error;
		});

		if (current && !current.isDirectory()) {
			throw new Error(`Pico webUI destination is not a directory: ${destination}`);
		}

		if (current) await rename(destination, previous);

		try {
			await rename(next, destination);
		} catch (error) {
			if (current) {
				try {
					await rename(previous, destination);
				} catch (rollbackError) {
					preserveBackup = true;

					throw new AggregateError(
						[error, rollbackError],
						`Pico package backup kept at ${previous}`
					);
				}
			}

			throw error;
		}

		return destination;
	} finally {
		if (!preserveBackup) await rm(transaction, { force: true, recursive: true });
	}
}
